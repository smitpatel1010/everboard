import Foundation

/// One coding-agent session (Claude Code, Cursor, or any tool with an adapter), as stored on disk.
///
/// This struct is also the file format: one JSON file per session in `SessionPaths.directory`.
/// `everboard-hook` writes these files for Claude Code and Cursor; other tools can write them directly.
/// See docs/agent-sessions.md. Decoding is lenient so older or hand-written files still load.
public struct AgentSession: Codable, Hashable, Sendable, Identifiable {
    public static let schemaVersion = 1

    public enum State: String, Codable, Sendable, CaseIterable {
        /// Started, no prompt yet.
        case idle
        case working
        /// Blocked on a permission prompt.
        case needsApproval = "needs_approval"
        /// The turn ended with a question, or the agent asked one mid-turn.
        case needsReply = "needs_reply"
        /// The turn ended without a question.
        case done
        case error
        /// The session or its process is gone.
        case ended

        public var needsYou: Bool { self == .needsApproval || self == .needsReply }

        public var label: String {
            switch self {
            case .idle: return "Idle"
            case .working: return "Working"
            case .needsApproval: return "Needs approval"
            case .needsReply: return "Waiting for you"
            case .done: return "Done"
            case .error: return "Error"
            case .ended: return "Ended"
            }
        }

        /// Sort order in lists: what needs you first, finished things last.
        public var rank: Int {
            switch self {
            case .needsApproval: return 0
            case .needsReply: return 1
            case .error: return 2
            case .working: return 3
            case .done: return 4
            case .idle: return 5
            case .ended: return 6
            }
        }
    }

    public var schema: Int
    /// Which agent: "claude-code", "cursor", or any id another adapter uses.
    public var tool: String
    /// The tool's own session or conversation id.
    public var sessionId: String
    public var state: State
    /// Session name, or the first prompt.
    public var title: String?
    /// The session's own name (set in the tool or generated by it), never prompt text. Shown even when
    /// prompts are hidden, so sessions in the same folder stay apart.
    public var name: String?
    /// The latest prompt.
    public var prompt: String?
    /// What it is doing right now, e.g. "Editing Select.swift".
    public var activity: String?
    /// The question, the approval it needs, the error, or a one-line summary of the last reply.
    public var detail: String?
    public var cwd: String?
    /// Every folder of the agent's workspace (Cursor windows can hold several).
    public var workspaceRoots: [String]?
    /// The agent's process, used to notice sessions that went away without saying so.
    public var pid: Int32?
    /// Bundle id of the app the agent runs in (a terminal, an editor, a desktop app), to bring it to the front.
    public var hostApp: String?
    /// The host app's own id for this session, when it has one (Claude's desktop app: `local_…`).
    public var hostSessionId: String?
    /// The agent's terminal device, e.g. `/dev/ttys003`, to find its tab and type replies into it.
    public var tty: String?
    public var transcriptPath: String?
    /// A shell command that reopens the session, when the tool has one.
    public var resumeCommand: String?
    /// A URL that opens the session or its workspace. Only `linkSchemes` are ever opened (see `safeOpenURL`).
    public var openURL: String?
    /// A tool call started and hasn't finished. Long waits here can mean an approval prompt the tool doesn't report.
    public var pendingSince: Date?
    /// Last assistant text seen mid-turn (tools that report it separately from the stop event).
    public var lastMessage: String?
    /// The open permission prompt, while the agent waits on one.
    public var approval: Approval?
    /// When the last prompt was answered; a permission notification after this is about that prompt.
    public var approvalResolvedAt: Date?
    /// The question came from a multiple-choice tool, so typing a free-text reply won't answer it.
    public var questionIsChoice: Bool?
    /// The most recent notice the agent recorded (a failed hook, an API error, an informational note).
    public var notice: Notice?
    /// Notices from before this time are resolved and not shown again.
    public var noticesClearedAt: Date?
    public var startedAt: Date
    public var updatedAt: Date
    /// When `state` last changed; part of event ids so each change notifies once.
    public var stateSince: Date

    public var id: String { "\(tool):\(sessionId)" }

    /// A permission prompt. While `holdUntil` is in the future the hook is holding it for Everboard to answer;
    /// after that the agent shows its own prompt.
    /// A prompt the agent is waiting on: a permission request, or a multiple-choice question (`questions` set).
    public struct Approval: Codable, Hashable, Sendable {
        public var id: String
        public var tool: String
        public var summary: String
        public var requestedAt: Date
        public var holdUntil: Date?
        /// The questions and their options, when the prompt is a question rather than a permission.
        public var questions: [ChoiceQuestion]?
        /// The tool's input as JSON, sent back with the answers.
        public var toolInput: String?

        public init(id: String, tool: String, summary: String, requestedAt: Date, holdUntil: Date? = nil,
                    questions: [ChoiceQuestion]? = nil, toolInput: String? = nil) {
            self.id = id
            self.tool = tool
            self.summary = summary
            self.requestedAt = requestedAt
            self.holdUntil = holdUntil
            self.questions = questions
            self.toolInput = toolInput
        }

        public var isQuestion: Bool { !(questions ?? []).isEmpty }

        public func isHeld(now: Date = Date()) -> Bool { (holdUntil ?? .distantPast) > now }
    }

    public struct ChoiceQuestion: Codable, Hashable, Sendable {
        public struct Option: Codable, Hashable, Sendable {
            public var label: String
            public var description: String?

            public init(label: String, description: String? = nil) {
                self.label = label
                self.description = description
            }
        }

        public var question: String
        public var header: String?
        public var multiSelect: Bool
        public var options: [Option]

        public init(question: String, header: String? = nil, multiSelect: Bool = false, options: [Option]) {
            self.question = question
            self.header = header
            self.multiSelect = multiSelect
            self.options = options
        }
    }

    public struct Notice: Codable, Hashable, Sendable {
        public enum Level: String, Codable, Sendable { case error, info }
        public enum Kind: String, Codable, Sendable { case hook, api, info }
        /// Stable id from the transcript entry, so each notice notifies once.
        public var id: String
        public var level: Level
        public var text: String
        public var at: Date
        /// API errors are retried by the agent, so a turn that ends normally resolves them.
        public var kind: Kind?

        /// Also recognises notices recorded before they had a kind.
        public var isAPIError: Bool { kind == .api || (kind == nil && text.hasPrefix("API error")) }

        public init(id: String, level: Level, text: String, at: Date, kind: Kind? = nil) {
            self.id = id
            self.level = level
            self.text = text
            self.at = at
            self.kind = kind
        }
    }

    public init(tool: String, sessionId: String, state: State = .idle, now: Date = Date()) {
        schema = Self.schemaVersion
        self.tool = tool
        self.sessionId = sessionId
        self.state = state
        startedAt = now
        updatedAt = now
        stateSince = now
    }

    /// Changes the state and records when, unless it is unchanged.
    public mutating func set(_ newState: State, at now: Date) {
        if newState != state { state = newState; stateSince = now }
    }

    /// Link schemes a click may open. Any tool can write a session file, so its link is never a `file:` URL
    /// (which could launch an app or script) or a scheme that mounts shares or changes settings.
    public static let linkSchemes: Set<String> = ["claude", "cursor", "vscode", "vscode-insiders", "vscodium", "windsurf", "zed", "https"]

    /// `openURL` when it's a link Everboard will open.
    public var safeOpenURL: URL? {
        guard let raw = openURL, let url = URL(string: raw), let scheme = url.scheme?.lowercased(),
              Self.linkSchemes.contains(scheme) else { return nil }
        return url
    }

    /// "Claude Code", "Cursor", or the id with its first letter capitalised.
    public var toolName: String { Self.toolName(tool) }

    public static func toolName(_ tool: String) -> String {
        switch tool {
        case "claude-code": return "Claude Code"
        case "cursor": return "Cursor"
        default:
            let words = tool.split(whereSeparator: { $0 == "-" || $0 == "_" }).map { $0.prefix(1).uppercased() + $0.dropFirst() }
            return words.isEmpty ? tool : words.joined(separator: " ")
        }
    }

    /// The folder name, for display ("everboard" for /path/to/everboard).
    public var project: String? {
        guard let cwd, !cwd.isEmpty else { return nil }
        return URL(fileURLWithPath: cwd).lastPathComponent
    }

    // MARK: Lenient decoding

    enum CodingKeys: String, CodingKey {
        case schema, tool, sessionId, state, title, name, prompt, activity, detail, cwd, workspaceRoots, pid, hostApp, hostSessionId, tty, transcriptPath
        case resumeCommand, openURL, pendingSince, lastMessage, approval, approvalResolvedAt, questionIsChoice, notice, noticesClearedAt, startedAt, updatedAt, stateSince
    }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        let now = Date()
        schema = (try? c.decodeIfPresent(Int.self, forKey: .schema)) ?? Self.schemaVersion
        tool = try c.decode(String.self, forKey: .tool)
        sessionId = try c.decode(String.self, forKey: .sessionId)
        let raw = (try? c.decodeIfPresent(String.self, forKey: .state)) ?? nil
        state = raw.flatMap(State.init(rawValue:)) ?? .working
        title = try? c.decodeIfPresent(String.self, forKey: .title)
        name = try? c.decodeIfPresent(String.self, forKey: .name)
        prompt = try? c.decodeIfPresent(String.self, forKey: .prompt)
        activity = try? c.decodeIfPresent(String.self, forKey: .activity)
        detail = try? c.decodeIfPresent(String.self, forKey: .detail)
        cwd = try? c.decodeIfPresent(String.self, forKey: .cwd)
        workspaceRoots = try? c.decodeIfPresent([String].self, forKey: .workspaceRoots)
        pid = try? c.decodeIfPresent(Int32.self, forKey: .pid)
        hostApp = try? c.decodeIfPresent(String.self, forKey: .hostApp)
        hostSessionId = try? c.decodeIfPresent(String.self, forKey: .hostSessionId)
        tty = try? c.decodeIfPresent(String.self, forKey: .tty)
        transcriptPath = try? c.decodeIfPresent(String.self, forKey: .transcriptPath)
        resumeCommand = try? c.decodeIfPresent(String.self, forKey: .resumeCommand)
        openURL = try? c.decodeIfPresent(String.self, forKey: .openURL)
        pendingSince = try? c.decodeIfPresent(Date.self, forKey: .pendingSince)
        lastMessage = try? c.decodeIfPresent(String.self, forKey: .lastMessage)
        approval = try? c.decodeIfPresent(Approval.self, forKey: .approval)
        approvalResolvedAt = try? c.decodeIfPresent(Date.self, forKey: .approvalResolvedAt)
        questionIsChoice = try? c.decodeIfPresent(Bool.self, forKey: .questionIsChoice)
        notice = try? c.decodeIfPresent(Notice.self, forKey: .notice)
        noticesClearedAt = try? c.decodeIfPresent(Date.self, forKey: .noticesClearedAt)
        let updated = (try? c.decodeIfPresent(Date.self, forKey: .updatedAt)) ?? nil
        updatedAt = updated ?? now
        startedAt = ((try? c.decodeIfPresent(Date.self, forKey: .startedAt)) ?? nil) ?? updatedAt
        stateSince = ((try? c.decodeIfPresent(Date.self, forKey: .stateSince)) ?? nil) ?? updatedAt
    }
}

/// Where session files and the hook binary live. No spaces in the default paths, so hook commands need no quoting.
public enum SessionPaths {
    /// `$EVERBOARD_SESSIONS_DIR`, else `$XDG_STATE_HOME/everboard/sessions`, else `~/.local/state/everboard/sessions`.
    public static func directory(environment: [String: String] = ProcessInfo.processInfo.environment,
                                 home: String = NSHomeDirectory()) -> URL {
        if let custom = environment["EVERBOARD_SESSIONS_DIR"], !custom.isEmpty {
            return URL(fileURLWithPath: (custom as NSString).expandingTildeInPath, isDirectory: true)
        }
        let state = environment["XDG_STATE_HOME"].flatMap { $0.isEmpty ? nil : $0 } ?? "\(home)/.local/state"
        return URL(fileURLWithPath: state, isDirectory: true).appendingPathComponent("everboard/sessions", isDirectory: true)
    }

    /// Written by the app every few seconds: tells hooks Everboard is running and whether to hold approvals.
    public static func appStatusFile(in directory: URL) -> URL { directory.appendingPathComponent(".everboard-app.json") }

    /// Answers to held approvals, one file per request, written by the app and consumed by the hook.
    public static func answersDirectory(in directory: URL) -> URL { directory.appendingPathComponent(".answers", isDirectory: true) }

    /// Stable location of the hook binary the tools call: `$XDG_DATA_HOME/everboard/bin/everboard-hook`
    /// (default `~/.local/share/...`). The app copies it there from its bundle, so moving the app doesn't break hooks.
    public static func hookBinary(environment: [String: String] = ProcessInfo.processInfo.environment,
                                  home: String = NSHomeDirectory()) -> URL {
        let data = environment["XDG_DATA_HOME"].flatMap { $0.isEmpty ? nil : $0 } ?? "\(home)/.local/share"
        return URL(fileURLWithPath: data, isDirectory: true).appendingPathComponent("everboard/bin/everboard-hook")
    }
}
